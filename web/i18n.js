  function translateInner(value) {
    let out = value;
    for (const [pattern, replacement] of INLINE_RULES) out = out.replace(pattern, replacement);
    for (const [key, translated] of Object.entries(DICT)) {
      if (out.includes(key)) out = out.split(key).join(translated);
    }
    for (const [pattern, replacement] of RULES) {
      const match = out.match(pattern);
      if (match && typeof replacement === "string") out = out.replace(pattern, replacement);
    }
    return out;
  }

  const ATTRS = ["placeholder", "title", "aria-label"];

  // 开头的图标符号与空白：几何图形、箭头、杂项符号、全角加号等。
  const PREFIX_RE = /^[\s\u00A0\u2000-\u27BF\u2B00-\u2BFF\uFE0F\uFF0B\uFF0D]+/;

  function translateText(text) {
    const trimmed = text.trim();
    if (!trimmed || !/[\u4e00-\u9fff]/.test(trimmed)) return text;
    const exact = DICT[trimmed];
    if (exact) return text.replace(trimmed, exact);
    // 按钮文本常把图标与文字放在同一个文本节点里（"↻ 刷新"、"＋ 新建"），
    // 精确匹配会因此落空。剥掉开头的符号与空白再查一次，命中后把前缀接回去——
    // 这样每加一个图标按钮都不必再补一条词条。
    const prefix = trimmed.match(PREFIX_RE);
    if (prefix) {
      const rest = trimmed.slice(prefix[0].length);
      const hit = rest && DICT[rest];
      if (hit) return text.replace(trimmed, prefix[0] + hit);
    }
    for (const [pattern, replacement] of RULES) {
      if (!pattern.test(trimmed)) continue;
      const replaced = typeof replacement === "function"
        ? trimmed.replace(pattern, replacement)
        : trimmed.replace(pattern, replacement);
      // 规则产出的文本里可能仍嵌着中文片段，再走一遍精确匹配。
      return text.replace(trimmed, DICT[replaced] || translateInner(replaced));
    }
    return text;
  }

  // 表格单元承载用户数据，输入控件承载用户输入：都不翻译，避免误伤数据。
  const SKIP = new Set(["INPUT", "TEXTAREA", "SCRIPT", "STYLE", "SELECT"]);

  function poTranslate(root) {
    if (!root || (window.displayLanguage || "zh") !== "en") return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
      acceptNode(node) {
        if (node.nodeType === Node.ELEMENT_NODE) {
          if (SKIP.has(node.tagName) || node.closest("[data-no-i18n]") || node.closest("td")) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_SKIP;
        }
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      const next = translateText(node.nodeValue);
      if (next !== node.nodeValue) node.nodeValue = next;
    }
    for (const element of root.querySelectorAll("[placeholder],[title],[aria-label]")) {
      if (element.closest("td") || element.closest("[data-no-i18n]")) continue;
      for (const attribute of ATTRS) {
        const value = element.getAttribute(attribute);
        if (!value) continue;
        const next = translateText(value);
        if (next !== value) element.setAttribute(attribute, next);
      }
    }
    for (const option of root.querySelectorAll("option")) {
      const next = translateText(option.textContent);
      if (next !== option.textContent) option.textContent = next;
    }
  }


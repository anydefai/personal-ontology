  // 动态插入的 DOM（局部更新、事件处理器里新生成的元素）不会经过渲染后的那一次遍历，
  // 因此保持中文（例如场景预演页选中实例后生成的「必填」标记）。这里监听 childList：
  // **只监听 childList，不监听 characterData**，否则文本替换本身会再次触发回调。
  function startObserver() {
    if (!window.MutationObserver || !document.body) return;
    new MutationObserver((records) => {
      if ((window.displayLanguage || "zh") !== "en") return;
      for (const record of records) {
        for (const node of record.addedNodes) {
          if (node.nodeType === 1) poTranslate(node);
          else if (node.nodeType === 3 && node.parentNode) poTranslate(node.parentNode);
        }
      }
    }).observe(document.body, { childList: true, subtree: true });
  }
